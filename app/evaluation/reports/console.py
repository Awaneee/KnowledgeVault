"""
Console report renderer.

Pretty-prints an EvaluationReport to stdout.

This module performs NO metric calculations.
It only formats the EvaluationReport generated by EvaluationRunner.
"""

from __future__ import annotations

from app.evaluation.models import EvaluationReport


class ConsoleReport:

    @staticmethod
    def render(report: EvaluationReport) -> None:

        print()
        print("=" * 90)
        print("KnowledgeVault Evaluation Report")
        print("=" * 90)

        print(f"Run ID        : {report.run_id}")
        print(f"Created At    : {report.created_at}")
        if report.git_commit:
            print(f"Git Commit    : {report.git_commit}")
        print(f"Benchmark Ver : {report.benchmark_version}")
        print(f"Queries       : {report.total_queries}")
        print(f"K             : {report.k}")
        if report.corpus_coverage > 0:
            print(f"Corpus Cov.   : {report.corpus_coverage:.1%}")

        print()

        for summary in report.summaries:

            print("-" * 90)

            print(
                f"Strategy : {summary.strategy.value.upper()}"
            )

            print("-" * 90)

            print(
                f"Queries Evaluated : {summary.query_count}"
            )

            print()

            print("Retrieval Metrics")

            print(
                f"  Precision@{report.k:<2} : "
                f"{summary.mean_precision_at_k:.3f}"
            )

            print(
                f"  Recall@{report.k:<2}    : "
                f"{summary.mean_recall_at_k:.3f}"
            )

            print(
                f"  Hit Rate      : "
                f"{summary.hit_rate:.3f}"
            )

            ci = summary.mrr_ci
            ci_str = f"  [{ci[0]:.3f}, {ci[1]:.3f}]" if ci else ""
            print(f"  MRR           : {summary.mrr:.3f}{ci_str}")
            print(f"  MAP@K         : {summary.mean_map_at_k:.3f}")
            print(f"  R-Precision   : {summary.mean_r_precision:.3f}")

            print()

            print("Classification")

            if summary.intent_accuracy is None:
                print("  Intent Accuracy   : N/A")
            else:
                print(
                    f"  Intent Accuracy   : "
                    f"{summary.intent_accuracy:.3f}"
                )

            if summary.category_accuracy is None:
                print("  Category Accuracy : N/A")
            else:
                print(
                    f"  Category Accuracy : "
                    f"{summary.category_accuracy:.3f}"
                )

            print()

            print("Latency")

            print(
                f"  Average : "
                f"{summary.avg_latency_ms:.2f} ms"
            )

            print(
                f"  Median  : "
                f"{summary.median_latency_ms:.2f} ms"
            )

            print(
                f"  P95     : "
                f"{summary.p95_latency_ms:.2f} ms"
            )

            print(
                f"  Max     : "
                f"{summary.max_latency_ms:.2f} ms"
            )

            print()

            print(
                f"Errors : {summary.error_count}"
            )

            print()

        print("=" * 90)

        print()

        print("Per Query Results")

        print("=" * 90)

        for evaluation in report.evaluations:

            print()

            print(
                f"[{evaluation.strategy.value.upper()}] "
                f"{evaluation.query}"
            )

            print(
                f"Benchmark : {evaluation.benchmark_id}"
            )

            print(
                f"Difficulty : {evaluation.difficulty}"
            )

            print()

            print(
                "Relevant Notes : "
                f"{evaluation.relevant_note_ids}"
            )

            print(
                "Retrieved Notes : "
                f"{evaluation.retrieved_note_ids}"
            )

            print()

            print(
                f"Precision@{report.k}: "
                f"{evaluation.precision_at_k:.3f}"
            )

            print(
                f"Recall@{report.k}: "
                f"{evaluation.recall_at_k:.3f}"
            )

            print(
                f"Hit : "
                f"{evaluation.hit}"
            )

            print(
                f"Reciprocal Rank : "
                f"{evaluation.reciprocal_rank:.3f}"
            )

            if evaluation.intent_correct is not None:

                print(
                    f"Intent : "
                    f"{evaluation.predicted_intent}"
                )

                print(
                    f"Expected Intent : "
                    f"{evaluation.expected_intent}"
                )

                print(
                    f"Intent Correct : "
                    f"{evaluation.intent_correct}"
                )

            if evaluation.category_correct is not None:

                print(
                    f"Category : "
                    f"{evaluation.predicted_category}"
                )

                print(
                    f"Expected Category : "
                    f"{evaluation.expected_category}"
                )

                print(
                    f"Category Correct : "
                    f"{evaluation.category_correct}"
                )

            print(
                f"Latency : "
                f"{evaluation.latency_ms:.2f} ms"
            )

            if evaluation.error:

                print()

                print("ERROR")

                print(evaluation.error)

            print("-" * 90)