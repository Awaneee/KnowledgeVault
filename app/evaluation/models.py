"""
Evaluation data models.

Pure Pydantic — no SQLAlchemy, no database tables.
Note IDs are integers matching the production notes.id column (Integer PK).
"""

from __future__ import annotations

from enum import Enum
from typing import Optional

from pydantic import BaseModel, Field


# ---------------------------------------------------------------------------
# Retrieval strategy enum
# ---------------------------------------------------------------------------

class RetrievalStrategy(str, Enum):
    """
    The three retrieval paths that exist in production:

    SEMANTIC  → EmbeddingService.search_notes()
                Returns note-level results ranked by pgvector similarity.

    INTENT    → IntentCategoryService.find_categories_for_query()
                Keyword-based query intent → category lookup → notes in
                that category. (The fast, no-LLM path used at query time.)

    HYBRID    → ChunkService.retrieve_hybrid()
                Intent-first then semantic fill, operating at chunk level.
                This is what AskService.ask() uses.
    """
    SEMANTIC = "semantic"
    INTENT = "intent"
    HYBRID = "hybrid"


# ---------------------------------------------------------------------------
# Benchmark input
# ---------------------------------------------------------------------------

class BenchmarkQuery(BaseModel):
    """
    A single labelled benchmark query.

    Fields
    ------
    id              Unique identifier for this benchmark entry.
    query           The natural-language query string sent to the pipeline.
    expected_intent The ground-truth intent_type string, one of
                    IntentExtractionService.INTENT_TYPES.
    expected_category
                    Human-readable category name the note should fall into.
                    Matches the names generated by
                    IntentCategoryService._generate_category_name().
    relevant_note_ids
                    Ordered list of note IDs (notes.id integers) that
                    constitute a correct answer. Order matters for MRR.
    difficulty      "easy" | "medium" | "hard"
    tags            Free-form tags for filtering benchmark subsets.
    """
    id: str
    query: str
    expected_intent: str
    expected_category: str
    relevant_note_ids: list[int] = Field(default_factory=list)
    difficulty: str = "medium"
    tags: list[str] = Field(default_factory=list)


# ---------------------------------------------------------------------------
# Retrieval output
# ---------------------------------------------------------------------------

class RetrievalResult(BaseModel):
    """
    Raw output from a single adapter call.

    Fields
    ------
    strategy        Which adapter produced this result.
    query           The query that was executed.
    retrieved_note_ids
                    Ordered list of note IDs returned by the adapter,
                    from most to least relevant.
    predicted_intent
                    intent_type string the adapter extracted for this query,
                    if applicable (INTENT and HYBRID paths supply this;
                    SEMANTIC does not).
    predicted_category
                    Category name the adapter matched for this query,
                    if applicable.
    latency_ms      Wall-clock time for the adapter call in milliseconds.
    error           Non-None if the adapter call raised an exception.
    """
    strategy: RetrievalStrategy
    query: str
    retrieved_note_ids: list[int] = Field(default_factory=list)
    predicted_intent: Optional[str] = None
    predicted_category: Optional[str] = None
    latency_ms: float = 0.0
    error: Optional[str] = None


# ---------------------------------------------------------------------------
# Per-query evaluation
# ---------------------------------------------------------------------------

class QueryEvaluation(BaseModel):
    """
    Metrics computed for a single (BenchmarkQuery, RetrievalResult) pair.
    """
    benchmark_id: str
    strategy: RetrievalStrategy
    query: str
    difficulty: str

    # Retrieval metrics (computed against relevant_note_ids)
    precision_at_k: float
    recall_at_k: float
    hit: bool                   # True if ≥1 relevant note in top-K
    reciprocal_rank: float      # 1/rank of first relevant note, 0 if none

    # Classification metrics (may be None for SEMANTIC which has no intent)
    intent_correct: Optional[bool] = None
    category_correct: Optional[bool] = None

    # Latency
    latency_ms: float

    # Pass-through for report rendering
    relevant_note_ids: list[int]
    retrieved_note_ids: list[int]
    predicted_intent: Optional[str] = None
    predicted_category: Optional[str] = None
    expected_intent: str
    expected_category: str

    error: Optional[str] = None


# ---------------------------------------------------------------------------
# Per-strategy aggregate
# ---------------------------------------------------------------------------

class StrategySummary(BaseModel):
    """
    Aggregated metrics across all queries for one RetrievalStrategy.
    """
    strategy: RetrievalStrategy
    query_count: int

    # Retrieval
    mean_precision_at_k: float
    mean_recall_at_k: float
    hit_rate: float
    mrr: float                  # Mean Reciprocal Rank

    # Classification (None for SEMANTIC)
    intent_accuracy: Optional[float] = None
    category_accuracy: Optional[float] = None

    # Latency
    avg_latency_ms: float
    median_latency_ms: float
    p95_latency_ms: float
    max_latency_ms: float

    error_count: int = 0


# ---------------------------------------------------------------------------
# Full evaluation report
# ---------------------------------------------------------------------------

class EvaluationReport(BaseModel):
    """
    Top-level result returned by the runner after evaluating all strategies.
    """
    run_id: str
    created_at: str             # ISO-8601 timestamp string
    k: int                      # K used for Precision@K / Recall@K
    total_queries: int

    # One entry per strategy
    summaries: list[StrategySummary]

    # All individual query evaluations (useful for CSV export / debugging)
    evaluations: list[QueryEvaluation]
